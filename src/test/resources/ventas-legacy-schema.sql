-- Esquema anterior a los importes decimales y al descuento de inventario.
CREATE TABLE productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL UNIQUE, descripcion VARCHAR(500),
    precio NUMERIC(10,2) NOT NULL, stock INTEGER NOT NULL,
    categoria VARCHAR(80) NOT NULL, activo BOOLEAN NOT NULL
);
CREATE TABLE ventas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha TIMESTAMP(6), total DOUBLE PRECISION
);
CREATE TABLE detalle_ventas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cantidad INTEGER NOT NULL, precio_unitario DOUBLE PRECISION,
    subtotal DOUBLE PRECISION, producto_id BIGINT NOT NULL, venta_id BIGINT,
    FOREIGN KEY (producto_id) REFERENCES productos(id),
    FOREIGN KEY (venta_id) REFERENCES ventas(id)
);
